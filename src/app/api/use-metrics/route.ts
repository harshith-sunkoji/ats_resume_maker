import { NextRequest, NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";
import { ResumeData } from "@/types/resume";

export const maxDuration = 60;

const USE_METRICS_SYSTEM_PROMPT = `
You are an elite resume coach and career strategist specialising in data-driven, impact-oriented resumes.

Your ONLY task: rewrite every bullet point in the candidate's "experiences" and "projects" arrays, and improve the "summary" paragraph, so they all contain SPECIFIC quantifiable metrics — percentages, dollar amounts, user counts, time reductions, throughput improvements, reliability figures, team sizes, or similar concrete numbers.

RULES:
1. Preserve the candidate's truthful context — only add metrics that are plausible and fit naturally.
2. Use realistic numbers based on industry norms (e.g. "reduced test runtime by 40%", "serving 10,000+ daily active users", "cut deployment time from 45 min to 8 min").
3. Every bullet must contain AT LEAST ONE numeric metric (%, $, x faster, N users, etc.).
4. Keep bullets concise — no longer than 2 lines.
5. DO NOT change: personalInfo, education, skillCategories, certifications, achievements, dates, company names, degrees, or any IDs.
6. Return ONLY a valid JSON object matching the exact same ResumeData schema. No markdown, no code fences.
`;

export async function POST(req: NextRequest) {
  try {
    const { resumeData } = (await req.json()) as { resumeData: ResumeData };

    if (!resumeData) {
      return NextResponse.json(
        { success: false, error: "No resume data provided." },
        { status: 400 }
      );
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { success: false, error: "GEMINI_API_KEY is not configured." },
        { status: 500 }
      );
    }

    const ai = new GoogleGenAI({ apiKey });

    const promptText = `
Candidate Resume JSON:
"""
${JSON.stringify(resumeData, null, 2)}
"""

Rewrite the experiences[*].bullets, projects[*].bullets, and summary fields to include quantifiable metrics. Return the complete updated ResumeData JSON.
`;

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: [
        {
          role: "user",
          parts: [
            { text: USE_METRICS_SYSTEM_PROMPT },
            { text: promptText },
          ],
        },
      ],
      config: {
        responseMimeType: "application/json",
      },
    });

    const outputText = response.text;
    if (!outputText) {
      throw new Error("No response content generated by Gemini AI.");
    }

    const cleanedText = outputText
      .replace(/^```json\s*/i, "")
      .replace(/```\s*$/, "")
      .trim();

    const updatedResumeData: ResumeData = JSON.parse(cleanedText);

    return NextResponse.json({ success: true, updatedResumeData });
  } catch (error: any) {
    console.error("Error in use-metrics route:", error);
    return NextResponse.json(
      {
        success: false,
        error: error.message || "Failed to enhance resume with metrics.",
      },
      { status: 500 }
    );
  }
}
